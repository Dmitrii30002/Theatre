UPDATE theatre.spectacles
SET description = 'Трагедия Уильяма Шекспира о принце Датском, стоящем перед выбором между местью, долгом и собственной совестью.'
WHERE id = 1
  AND (description IS NULL OR description = '');

UPDATE theatre.spectacles
SET description = CASE id
    WHEN 2 THEN 'Балетная сказка о рождественском чуде, Щелкунчике и путешествии в волшебный мир.'
    WHEN 3 THEN 'История любви, свободы и выбора, происходящая в Москве и наполненная мистикой.'
    WHEN 4 THEN 'Трагедия о принце Датском, его сомнениях и поиске справедливости.'
    WHEN 5 THEN 'Праздничный балет о чудесах, дружбе и победе добра.'
    WHEN 6 THEN 'Мистическая история о любви, свободе и цене человеческого выбора.'
END
WHERE id IN (2, 3, 4, 5, 6)
  AND (description IS NULL OR description = '');